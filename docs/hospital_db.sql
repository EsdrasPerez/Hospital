-- =====================================================================
-- HOSPITAL (Urgencias + Clínica + Hospitalización) - PostgreSQL 14+
-- Adaptado a Guatemala: DPI, NIT, número de colegiado, IVA 12 %, moneda GTQ.
--
-- Uso:
--   createdb -U postgres hospital_db
--   psql -U postgres -d hospital_db -f hospital_db.sql
--
-- Nota: los INSERT de datos de ejemplo están al final del archivo.
-- =====================================================================

-- =====================================================================
-- 1. CATÁLOGOS
-- =====================================================================

CREATE TABLE tipos_sangre (
    id_tipo_sangre INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion    VARCHAR(5) NOT NULL UNIQUE
);

CREATE TABLE estados_cita (
    id_estado_cita INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion    VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE estados_habitacion (
    id_estado_habitacion INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion          VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE tipos_habitacion (
    id_tipo_habitacion INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion        VARCHAR(50) NOT NULL UNIQUE,
    costo_dia          NUMERIC(10,2) NOT NULL CHECK (costo_dia >= 0)  -- en quetzales (GTQ)
);

CREATE TABLE turnos (
    id_turno    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion VARCHAR(30) NOT NULL UNIQUE,
    hora_inicio TIME NOT NULL,
    hora_fin    TIME NOT NULL
);

CREATE TABLE niveles_urgencia (
    id_nivel_urgencia     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo                VARCHAR(5) NOT NULL UNIQUE,      -- N1..N5
    descripcion           VARCHAR(100) NOT NULL,
    tiempo_max_espera_min INT NOT NULL CHECK (tiempo_max_espera_min >= 0),
    color                 VARCHAR(20)
);

CREATE TABLE estados_emergencia (
    id_estado_emergencia INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion          VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE destinos_alta (
    id_destino_alta INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion     VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE estados_hospitalizacion (
    id_estado_hosp INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion    VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE tipos_diagnostico (
    id_tipo_diagnostico INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion         VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE metodos_pago (
    id_metodo_pago INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion    VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE estados_factura (
    id_estado_factura INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion       VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE roles_usuario (
    id_rol      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion VARCHAR(30) NOT NULL UNIQUE
);

-- =====================================================================
-- 2. ESTRUCTURA ORGANIZACIONAL
-- =====================================================================

CREATE TABLE departamentos (
    id_departamento INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(100) NOT NULL UNIQUE,
    ubicacion       VARCHAR(100),
    telefono        VARCHAR(20)
);

CREATE TABLE clinicas (
    id_clinica      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(100) NOT NULL UNIQUE,
    descripcion     TEXT,
    id_departamento INT NOT NULL REFERENCES departamentos(id_departamento),
    ubicacion       VARCHAR(100),
    telefono        VARCHAR(20),
    activa          BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE especialidades (
    id_especialidad INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(100) NOT NULL UNIQUE,
    descripcion     TEXT,
    id_clinica      INT REFERENCES clinicas(id_clinica)
);

-- =====================================================================
-- 3. PACIENTES
-- =====================================================================

CREATE TABLE pacientes (
    id_paciente          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_expediente    VARCHAR(20) NOT NULL UNIQUE,
    nombre               VARCHAR(100) NOT NULL,
    apellido_paterno     VARCHAR(100) NOT NULL,
    apellido_materno     VARCHAR(100),
    fecha_nacimiento     DATE NOT NULL CHECK (fecha_nacimiento <= CURRENT_DATE),
    sexo                 CHAR(1) NOT NULL CHECK (sexo IN ('M','F','O')),
    dpi                  CHAR(13) UNIQUE CHECK (dpi ~ '^[0-9]{13}$'),  -- NULL para menores sin DPI
    nit                  VARCHAR(13),                                  -- para facturar; NULL = CF
    telefono             VARCHAR(20),
    email                VARCHAR(100),
    direccion            TEXT,
    id_tipo_sangre       INT REFERENCES tipos_sangre(id_tipo_sangre),
    contacto_emergencia  VARCHAR(150),
    telefono_emergencia  VARCHAR(20),
    fecha_registro       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE alergias (
    id_alergia  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion VARCHAR(150) NOT NULL UNIQUE
);

CREATE TABLE paciente_alergia (
    id_paciente   INT NOT NULL REFERENCES pacientes(id_paciente) ON DELETE CASCADE,
    id_alergia    INT NOT NULL REFERENCES alergias(id_alergia),
    observaciones VARCHAR(200),
    PRIMARY KEY (id_paciente, id_alergia)
);

-- =====================================================================
-- 4. PERSONAL
-- =====================================================================

CREATE TABLE medicos (
    id_medico         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_colegiado  VARCHAR(30) NOT NULL UNIQUE,   -- Colegio de Médicos y Cirujanos de Guatemala
    nombre            VARCHAR(100) NOT NULL,
    apellido_paterno  VARCHAR(100) NOT NULL,
    apellido_materno  VARCHAR(100),
    telefono          VARCHAR(20),
    email             VARCHAR(100),
    activo            BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE medico_especialidad (
    id_medico       INT NOT NULL REFERENCES medicos(id_medico) ON DELETE CASCADE,
    id_especialidad INT NOT NULL REFERENCES especialidades(id_especialidad),
    es_principal    BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (id_medico, id_especialidad)
);

-- Horario semanal de atención (permite validar que una cita caiga en horario laboral)
CREATE TABLE horarios_medico (
    id_horario  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_medico   INT NOT NULL REFERENCES medicos(id_medico) ON DELETE CASCADE,
    id_clinica  INT REFERENCES clinicas(id_clinica),
    dia_semana  SMALLINT NOT NULL CHECK (dia_semana BETWEEN 1 AND 7),  -- 1 = lunes ... 7 = domingo
    hora_inicio TIME NOT NULL,
    hora_fin    TIME NOT NULL,
    CHECK (hora_fin > hora_inicio),
    UNIQUE (id_medico, dia_semana, hora_inicio)
);

CREATE TABLE enfermeros (
    id_enfermero      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_colegiado  VARCHAR(30) NOT NULL UNIQUE,
    nombre            VARCHAR(100) NOT NULL,
    apellido_paterno  VARCHAR(100) NOT NULL,
    apellido_materno  VARCHAR(100),
    telefono          VARCHAR(20),
    id_departamento   INT REFERENCES departamentos(id_departamento),
    activo            BOOLEAN NOT NULL DEFAULT TRUE
);

-- =====================================================================
-- 5. HABITACIONES
-- =====================================================================

CREATE TABLE habitaciones (
    id_habitacion        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero               VARCHAR(10) NOT NULL UNIQUE,
    piso                 INT NOT NULL,
    id_tipo_habitacion   INT NOT NULL REFERENCES tipos_habitacion(id_tipo_habitacion),
    capacidad            INT NOT NULL DEFAULT 1 CHECK (capacidad > 0),
    id_estado_habitacion INT NOT NULL REFERENCES estados_habitacion(id_estado_habitacion)
);

-- =====================================================================
-- 6. CLÍNICA: CITAS Y CONSULTAS
-- (La regla "un médico no puede tener dos citas activas a la misma hora"
--  se valida en la capa de servicios, porque una cita cancelada libera el horario.)
-- =====================================================================

CREATE TABLE citas (
    id_cita        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente    INT NOT NULL REFERENCES pacientes(id_paciente),
    id_medico      INT NOT NULL REFERENCES medicos(id_medico),
    id_clinica     INT NOT NULL REFERENCES clinicas(id_clinica),
    fecha          DATE NOT NULL,
    hora           TIME NOT NULL,
    motivo         VARCHAR(255),
    id_estado_cita INT NOT NULL REFERENCES estados_cita(id_estado_cita),
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_citas_medico_fecha ON citas(id_medico, fecha, hora);
CREATE INDEX idx_citas_paciente     ON citas(id_paciente);

CREATE TABLE consultas (
    id_consulta         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente         INT NOT NULL REFERENCES pacientes(id_paciente),
    id_medico           INT NOT NULL REFERENCES medicos(id_medico),
    id_cita             INT REFERENCES citas(id_cita),
    id_clinica          INT REFERENCES clinicas(id_clinica),
    fecha_hora          TIMESTAMP NOT NULL,
    sintomas            TEXT,
    peso                NUMERIC(5,2),
    talla               NUMERIC(5,2),
    temperatura         NUMERIC(4,2),
    presion_arterial    VARCHAR(20),
    frecuencia_cardiaca INT,
    notas               TEXT
);
CREATE INDEX idx_consultas_paciente ON consultas(id_paciente);

-- =====================================================================
-- 7. EMERGENCIAS
-- =====================================================================

CREATE TABLE emergencias (
    id_emergencia        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente          INT REFERENCES pacientes(id_paciente),   -- NULL si aún no tiene expediente
    nombre_temporal      VARCHAR(150),                            -- paciente no identificado
    fecha_hora_ingreso   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    motivo               TEXT NOT NULL,
    id_nivel_urgencia    INT NOT NULL REFERENCES niveles_urgencia(id_nivel_urgencia),
    id_estado_emergencia INT NOT NULL REFERENCES estados_emergencia(id_estado_emergencia),
    id_medico_triage     INT REFERENCES medicos(id_medico),
    id_medico_tratante   INT REFERENCES medicos(id_medico),
    id_habitacion        INT REFERENCES habitaciones(id_habitacion),  -- observación / trauma
    fecha_hora_alta      TIMESTAMP,
    id_destino_alta      INT REFERENCES destinos_alta(id_destino_alta),
    CHECK (id_paciente IS NOT NULL OR nombre_temporal IS NOT NULL),
    CHECK (fecha_hora_alta IS NULL OR fecha_hora_alta >= fecha_hora_ingreso)
);
CREATE INDEX idx_emergencias_ingreso ON emergencias(fecha_hora_ingreso);
CREATE INDEX idx_emergencias_estado  ON emergencias(id_estado_emergencia, id_nivel_urgencia);

-- Historial de triaje con signos vitales estructurados
CREATE TABLE triaje_registros (
    id_triaje              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_emergencia          INT NOT NULL REFERENCES emergencias(id_emergencia) ON DELETE CASCADE,
    id_nivel_urgencia      INT NOT NULL REFERENCES niveles_urgencia(id_nivel_urgencia),
    id_medico              INT NOT NULL REFERENCES medicos(id_medico),
    fecha_hora             TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    temperatura            NUMERIC(4,2),
    presion_arterial       VARCHAR(20),
    frecuencia_cardiaca    INT,
    frecuencia_respiratoria INT,
    saturacion_oxigeno     INT CHECK (saturacion_oxigeno BETWEEN 0 AND 100),
    observaciones          TEXT
);

CREATE TABLE procedimientos_emergencia (
    id_procedimiento INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_emergencia    INT NOT NULL REFERENCES emergencias(id_emergencia) ON DELETE CASCADE,
    descripcion      VARCHAR(200) NOT NULL,
    fecha_hora       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_medico        INT NOT NULL REFERENCES medicos(id_medico),
    observaciones    TEXT
);

-- =====================================================================
-- 8. HOSPITALIZACIÓN (puede originarse en una emergencia)
-- =====================================================================

CREATE TABLE hospitalizaciones (
    id_hospitalizacion    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente           INT NOT NULL REFERENCES pacientes(id_paciente),
    id_emergencia         INT REFERENCES emergencias(id_emergencia),   -- origen, si vino de urgencias
    id_habitacion         INT NOT NULL REFERENCES habitaciones(id_habitacion),
    id_medico_responsable INT NOT NULL REFERENCES medicos(id_medico),
    id_clinica            INT REFERENCES clinicas(id_clinica),
    fecha_ingreso         TIMESTAMP NOT NULL,
    fecha_alta            TIMESTAMP,
    motivo_ingreso        TEXT,
    id_estado_hosp        INT NOT NULL REFERENCES estados_hospitalizacion(id_estado_hosp),
    CHECK (fecha_alta IS NULL OR fecha_alta >= fecha_ingreso)
);
CREATE INDEX idx_hosp_paciente   ON hospitalizaciones(id_paciente);
CREATE INDEX idx_hosp_habitacion ON hospitalizaciones(id_habitacion);

CREATE TABLE asignacion_enfermeros (
    id_asignacion      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_enfermero       INT NOT NULL REFERENCES enfermeros(id_enfermero),
    id_hospitalizacion INT NOT NULL REFERENCES hospitalizaciones(id_hospitalizacion) ON DELETE CASCADE,
    fecha_asignacion   DATE NOT NULL,
    id_turno           INT NOT NULL REFERENCES turnos(id_turno),
    UNIQUE (id_enfermero, fecha_asignacion, id_turno, id_hospitalizacion)
);

-- =====================================================================
-- 9. DIAGNÓSTICOS Y TRATAMIENTOS
-- Un diagnóstico pertenece a UNA consulta, emergencia u hospitalización.
-- =====================================================================

CREATE TABLE diagnosticos (
    id_diagnostico      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_consulta         INT REFERENCES consultas(id_consulta),
    id_emergencia       INT REFERENCES emergencias(id_emergencia),
    id_hospitalizacion  INT REFERENCES hospitalizaciones(id_hospitalizacion),
    codigo_cie10        VARCHAR(10),
    descripcion         TEXT NOT NULL,
    id_tipo_diagnostico INT NOT NULL REFERENCES tipos_diagnostico(id_tipo_diagnostico),
    fecha               DATE NOT NULL DEFAULT CURRENT_DATE,
    CHECK (num_nonnulls(id_consulta, id_emergencia, id_hospitalizacion) = 1)
);

CREATE TABLE tratamientos (
    id_tratamiento INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_diagnostico INT NOT NULL REFERENCES diagnosticos(id_diagnostico),
    descripcion    TEXT NOT NULL,
    duracion_dias  INT CHECK (duracion_dias > 0),
    indicaciones   TEXT,
    fecha_inicio   DATE,
    fecha_fin      DATE,
    CHECK (fecha_fin IS NULL OR fecha_inicio IS NULL OR fecha_fin >= fecha_inicio)
);

-- =====================================================================
-- 10. FARMACIA
-- =====================================================================

CREATE TABLE medicamentos (
    id_medicamento   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_comercial VARCHAR(150) NOT NULL,
    nombre_generico  VARCHAR(150) NOT NULL,
    presentacion     VARCHAR(100),
    concentracion    VARCHAR(50),
    laboratorio      VARCHAR(100),
    stock            INT NOT NULL DEFAULT 0 CHECK (stock >= 0),
    stock_minimo     INT NOT NULL DEFAULT 10,
    precio           NUMERIC(10,2) CHECK (precio >= 0),          -- GTQ
    requiere_receta  BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE recetas (
    id_receta      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_consulta    INT REFERENCES consultas(id_consulta),
    id_emergencia  INT REFERENCES emergencias(id_emergencia),
    id_medicamento INT NOT NULL REFERENCES medicamentos(id_medicamento),
    dosis          VARCHAR(100) NOT NULL,
    frecuencia     VARCHAR(100) NOT NULL,
    duracion       VARCHAR(50),
    cantidad       INT CHECK (cantidad > 0),
    indicaciones   TEXT,
    CHECK (id_consulta IS NOT NULL OR id_emergencia IS NOT NULL)
);

-- =====================================================================
-- 11. FACTURACIÓN Y PAGOS
-- Una factura cubre una consulta, una emergencia y/o una hospitalización.
-- IVA Guatemala = 12 %. NIT 'CF' = consumidor final.
-- =====================================================================

CREATE TABLE facturas (
    id_factura          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_factura      VARCHAR(30) NOT NULL UNIQUE,
    id_paciente         INT NOT NULL REFERENCES pacientes(id_paciente),
    id_consulta         INT REFERENCES consultas(id_consulta),
    id_emergencia       INT REFERENCES emergencias(id_emergencia),
    id_hospitalizacion  INT REFERENCES hospitalizaciones(id_hospitalizacion),
    nit_cliente         VARCHAR(13) NOT NULL DEFAULT 'CF',
    nombre_facturacion  VARCHAR(150) NOT NULL,
    fecha_emision       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    subtotal            NUMERIC(10,2) NOT NULL CHECK (subtotal >= 0),
    iva                 NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (iva >= 0),
    total               NUMERIC(10,2) NOT NULL CHECK (total >= 0),
    id_estado_factura   INT NOT NULL REFERENCES estados_factura(id_estado_factura),
    CHECK (num_nonnulls(id_consulta, id_emergencia, id_hospitalizacion) >= 1),
    CHECK (total = subtotal + iva)
);
CREATE INDEX idx_facturas_paciente ON facturas(id_paciente);

CREATE TABLE detalle_factura (
    id_detalle      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_factura      INT NOT NULL REFERENCES facturas(id_factura) ON DELETE CASCADE,
    concepto        VARCHAR(200) NOT NULL,
    cantidad        INT NOT NULL DEFAULT 1 CHECK (cantidad > 0),
    precio_unitario NUMERIC(10,2) NOT NULL CHECK (precio_unitario >= 0),
    importe         NUMERIC(10,2) NOT NULL CHECK (importe >= 0)
);

-- Pagos parciales o múltiples por factura
CREATE TABLE pagos (
    id_pago        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_factura     INT NOT NULL REFERENCES facturas(id_factura),
    id_metodo_pago INT NOT NULL REFERENCES metodos_pago(id_metodo_pago),
    monto          NUMERIC(10,2) NOT NULL CHECK (monto > 0),
    fecha_pago     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    referencia     VARCHAR(100)                                   -- no. de boleta, autorización, etc.
);
CREATE INDEX idx_pagos_factura ON pagos(id_factura);

-- =====================================================================
-- 12. USUARIOS DEL SISTEMA
-- =====================================================================

CREATE TABLE usuarios (
    id_usuario     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       VARCHAR(50) NOT NULL UNIQUE,
    password_hash  VARCHAR(255) NOT NULL,                         -- BCrypt, nunca texto plano
    id_rol         INT NOT NULL REFERENCES roles_usuario(id_rol),
    id_medico      INT REFERENCES medicos(id_medico),
    id_enfermero   INT REFERENCES enfermeros(id_enfermero),
    activo         BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ultimo_acceso  TIMESTAMP,
    CHECK (num_nonnulls(id_medico, id_enfermero) <= 1)
);

