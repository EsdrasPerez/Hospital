CHARACTER SET utf8mb4 
COLLATE utf8mb4_unicode_ci;
USE hospital_db;

-- =====================================================
-- CATÁLOGOS (eliminan dependencias transitivas → 3FN)
-- =====================================================
CREATE TABLE rol (
                     id_rol BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                     nombre VARCHAR(50) NOT NULL UNIQUE,
                     descripcion VARCHAR(200),
                     activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE tipo_sangre (
                             id_tipo_de_sangre BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             nombre VARCHAR(10) NOT NULL UNIQUE,          -- Ej: O+, A-, AB+
                             descripcion VARCHAR(200),
                             activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE alergias (
                          id_alergias BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          nombre VARCHAR(100) NOT NULL UNIQUE,
                          descripcion VARCHAR(255),
                          activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE estado_cita (
                             id_estado BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             nombre VARCHAR(30) NOT NULL UNIQUE,          -- Ej: Programada, Atendida, Cancelada
                             descripcion VARCHAR(200),
                             activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE estado_habitacion (
                                   id_estado_habitacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                   nombre VARCHAR(30) NOT NULL UNIQUE,          -- Ej: Disponible, Ocupada, Mantenimiento
                                   descripcion VARCHAR(200),
                                   activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE triaje (
                        id_triaje BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        nivel_de_emergencia VARCHAR(50) NOT NULL,
                        descripcion VARCHAR(255),
                        activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE especialidad_medico (
                                     id_especialidad BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                     nombre VARCHAR(100) NOT NULL UNIQUE,
                                     descripcion VARCHAR(255),
                                     activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE especialidad_clinica (
                                      id_especialidad BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                      nombre VARCHAR(100) NOT NULL UNIQUE,
                                      descripcion VARCHAR(255),
                                      activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE departamentos (
                               id_departamento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               nombre VARCHAR(100) NOT NULL UNIQUE,
                               descripcion VARCHAR(255),
                               telefono VARCHAR(20),
                               estado BOOLEAN NOT NULL DEFAULT TRUE
);

-- Catálogos del script anterior
CREATE TABLE tipos_habitacion (
                                  id_tipo_habitacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  descripcion VARCHAR(50) NOT NULL UNIQUE,
                                  costo_dia DECIMAL(10,2) NOT NULL CHECK (costo_dia >= 0),
                                  activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE turnos (
                        id_turno BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        descripcion VARCHAR(30) NOT NULL UNIQUE,
                        hora_inicio TIME NOT NULL,
                        hora_fin TIME NOT NULL,
                        activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE niveles_urgencia (
                                  id_nivel_urgencia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  codigo VARCHAR(5) NOT NULL UNIQUE,           -- Ej: N1, N2, N3
                                  descripcion VARCHAR(100) NOT NULL,
                                  tiempo_max_espera_min INT NOT NULL CHECK (tiempo_max_espera_min >= 0),
                                  color VARCHAR(20),
                                  activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE estados_hospitalizacion (
                                         id_estado_hosp BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         descripcion VARCHAR(30) NOT NULL UNIQUE,
                                         activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE tipos_diagnostico (
                                   id_tipo_diagnostico BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                   descripcion VARCHAR(30) NOT NULL UNIQUE,
                                   activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE metodos_pago (
                              id_metodo_pago BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              descripcion VARCHAR(50) NOT NULL UNIQUE,
                              activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE estados_factura (
                                 id_estado_factura BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 descripcion VARCHAR(30) NOT NULL UNIQUE,
                                 activo BOOLEAN NOT NULL DEFAULT TRUE
);

-- =====================================================
-- USUARIOS
-- =====================================================

CREATE TABLE usuarios (
                          id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          nombre_usuario VARCHAR(50) NOT NULL UNIQUE,
                          contrasena_hash VARCHAR(255) NOT NULL,
                          estado BOOLEAN NOT NULL DEFAULT TRUE,
                          ultimo_acceso TIMESTAMP,
                          id_rol BIGINT NOT NULL REFERENCES rol(id_rol)
);

-- =====================================================
-- PACIENTE
-- =====================================================

CREATE TABLE paciente (
                          id_paciente BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          dpi_paciente VARCHAR(13) NOT NULL UNIQUE,
                          nombre VARCHAR(100) NOT NULL,
                          apellido_paterno VARCHAR(100) NOT NULL,
                          apellido_materno VARCHAR(100) NOT NULL,
                          fecha_nacimiento DATE,
                          sexo CHAR(1) NOT NULL CHECK (sexo IN ('M', 'F')),
                          telefono VARCHAR(20) NOT NULL,
                          correo_electronico VARCHAR(150),
                          direccion VARCHAR(255),
                          fecha_registro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                          id_alergias BIGINT REFERENCES alergias(id_alergias),
                          id_tipo_de_sangre BIGINT REFERENCES tipo_sangre(id_tipo_de_sangre),
                          activo BOOLEAN NOT NULL DEFAULT TRUE
);

-- =====================================================
-- MÉDICO, CLÍNICAS Y ENFERMEROS
-- =====================================================

CREATE TABLE medico (
                        id_medico BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        no_colegiado VARCHAR(30) NOT NULL UNIQUE,
                        nombre VARCHAR(100) NOT NULL,
                        apellido_paterno VARCHAR(100) NOT NULL,
                        apellido_materno VARCHAR(100),
                        telefono VARCHAR(20),
                        email VARCHAR(150),
                        estado BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE medico_especialidades (
                                       id_especialidad BIGINT NOT NULL REFERENCES especialidad_medico(id_especialidad),
                                       id_medico BIGINT NOT NULL REFERENCES medico(id_medico) ON DELETE CASCADE,
                                       PRIMARY KEY (id_especialidad, id_medico)
);

CREATE TABLE clinicas (
                          id_clinica BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          nombre VARCHAR(100) NOT NULL,
                          descripcion VARCHAR(255),
                          ubicacion VARCHAR(255),
                          telefono VARCHAR(20),
                          estado_clinica BOOLEAN NOT NULL DEFAULT TRUE,
                          id_departamento BIGINT REFERENCES departamentos(id_departamento),
                          id_especialidad BIGINT REFERENCES especialidad_clinica(id_especialidad)
);

CREATE TABLE enfermeros (
                            id_enfermero BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            cedula_profesional VARCHAR(30) NOT NULL UNIQUE,
                            nombre VARCHAR(100) NOT NULL,
                            apellido_paterno VARCHAR(100) NOT NULL,
                            apellido_materno VARCHAR(100),
                            telefono VARCHAR(20),
                            id_departamento BIGINT REFERENCES departamentos(id_departamento),
                            activo BOOLEAN NOT NULL DEFAULT TRUE
);

-- =====================================================
-- CITAS Y CONSULTAS
-- =====================================================

CREATE TABLE citas (
                       id_cita BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       fecha DATE NOT NULL,
                       hora TIME NOT NULL,
                       motivo VARCHAR(255),
                       fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                       id_estado BIGINT NOT NULL REFERENCES estado_cita(id_estado),
                       id_medico BIGINT NOT NULL REFERENCES medico(id_medico),
                       id_paciente BIGINT NOT NULL REFERENCES paciente(id_paciente),
                       activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE consultas (
                           id_consulta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           fecha_hora TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                           sintomas TEXT,
                           peso DECIMAL(5,2),                -- kg
                           talla DECIMAL(5,2),               -- cm
                           temperatura DECIMAL(4,1),         -- °C
                           presion_arterial VARCHAR(10),     -- Ej: 120/80
                           frecuencia_cardiaca INT,          -- latidos por minuto
                           id_cita BIGINT NOT NULL REFERENCES citas(id_cita),
                           activo BOOLEAN NOT NULL DEFAULT TRUE
);

-- =====================================================
-- DIAGNÓSTICOS, TRATAMIENTOS Y MEDICAMENTOS
-- =====================================================

CREATE TABLE diagnosticos (
                              id_diagnostico BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              observaciones TEXT,
                              id_tipo_diagnostico BIGINT NOT NULL REFERENCES tipos_diagnostico(id_tipo_diagnostico),
                              descripcion VARCHAR(255) NOT NULL,
                              fecha DATE NOT NULL DEFAULT CURRENT_DATE,
                              activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE diagnostico_consulta (
                                      id_diagnostico BIGINT NOT NULL REFERENCES diagnosticos(id_diagnostico),
                                      id_consulta BIGINT NOT NULL REFERENCES consultas(id_consulta) ON DELETE CASCADE,
                                      PRIMARY KEY (id_diagnostico, id_consulta)
);

CREATE TABLE tratamiento (
                             id_tratamiento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             descripcion VARCHAR(255) NOT NULL,
                             duracion_dias INT CHECK (duracion_dias > 0),
                             indicaciones TEXT,
                             fecha_inicio DATE,
                             fecha_fin DATE,
                             id_diagnostico BIGINT NOT NULL REFERENCES diagnosticos(id_diagnostico),
                             activo BOOLEAN NOT NULL DEFAULT TRUE,
                             CHECK (fecha_fin IS NULL OR fecha_inicio IS NULL OR fecha_fin >= fecha_inicio)
);

CREATE TABLE medicamentos (
                              id_medicamento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              nombre_comercial VARCHAR(150) NOT NULL,
                              nombre_generico VARCHAR(150),
                              presentacion VARCHAR(100),
                              laboratorio VARCHAR(100),
                              stock INT NOT NULL DEFAULT 0 CHECK (stock >= 0),
                              stock_minimo INT NOT NULL DEFAULT 0 CHECK (stock_minimo >= 0),
                              precio DECIMAL(10,2) NOT NULL DEFAULT 0 CHECK (precio >= 0),
                              requiere_receta BOOLEAN NOT NULL DEFAULT FALSE,
                              activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE tratamiento_medicamento (
                                         id_medicamento BIGINT NOT NULL REFERENCES medicamentos(id_medicamento),
                                         id_tratamiento BIGINT NOT NULL REFERENCES tratamiento(id_tratamiento) ON DELETE CASCADE,
                                         PRIMARY KEY (id_medicamento, id_tratamiento)
);

-- =====================================================
-- HABITACIÓN Y EMERGENCIA
-- =====================================================

CREATE TABLE habitacion (
                            id_habitacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            numero VARCHAR(10) NOT NULL UNIQUE,
                            piso INT NOT NULL,
                            capacidad INT NOT NULL DEFAULT 1 CHECK (capacidad > 0),
                            id_estado_habitacion BIGINT NOT NULL REFERENCES estado_habitacion(id_estado_habitacion),
                            activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE emergencia (
                            id_emergencia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            nombre_temporal VARCHAR(150),
                            fecha_hora_ingreso TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                            motivo TEXT,
                            signos_vitales TEXT,
                            fecha_hora_alta TIMESTAMP,
                            id_paciente BIGINT REFERENCES paciente(id_paciente),
                            id_habitacion BIGINT REFERENCES habitacion(id_habitacion),
                            id_medico BIGINT REFERENCES medico(id_medico),
                            id_triaje BIGINT NOT NULL REFERENCES triaje(id_triaje),
                            activo BOOLEAN NOT NULL DEFAULT TRUE,
                            CHECK (fecha_hora_alta IS NULL OR fecha_hora_alta >= fecha_hora_ingreso)
);

CREATE TABLE procedimientos_emergencia (
                                           id_procedimiento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                           id_emergencia BIGINT NOT NULL REFERENCES emergencia(id_emergencia) ON DELETE CASCADE,
                                           descripcion VARCHAR(200) NOT NULL,
                                           fecha_hora TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                           id_medico BIGINT NOT NULL REFERENCES medico(id_medico),
                                           observaciones TEXT,
                                           activo BOOLEAN NOT NULL DEFAULT TRUE
);

-- =====================================================
-- HOSPITALIZACIÓN
-- =====================================================

CREATE TABLE hospitalizaciones (
                                   id_hospitalizacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                   id_paciente BIGINT NOT NULL REFERENCES paciente(id_paciente),
                                   id_habitacion BIGINT NOT NULL REFERENCES habitacion(id_habitacion),
                                   id_medico_responsable BIGINT NOT NULL REFERENCES medico(id_medico),
                                   id_clinica BIGINT REFERENCES clinicas(id_clinica),
                                   fecha_ingreso TIMESTAMP NOT NULL,
                                   fecha_alta TIMESTAMP,
                                   motivo_ingreso TEXT,
                                   diagnostico_ingreso TEXT,
                                   id_estado_hosp BIGINT NOT NULL REFERENCES estados_hospitalizacion(id_estado_hosp),
                                   activo BOOLEAN NOT NULL DEFAULT TRUE,
                                   CHECK (fecha_alta IS NULL OR fecha_alta >= fecha_ingreso)
);

CREATE TABLE asignacion_enfermeros (
                                       id_asignacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                       id_enfermero BIGINT NOT NULL REFERENCES enfermeros(id_enfermero),
                                       id_hospitalizacion BIGINT NOT NULL REFERENCES hospitalizaciones(id_hospitalizacion) ON DELETE CASCADE,
                                       fecha_asignacion DATE NOT NULL,
                                       id_turno BIGINT NOT NULL REFERENCES turnos(id_turno),
                                       activo BOOLEAN NOT NULL DEFAULT TRUE,
                                       UNIQUE (id_enfermero, id_hospitalizacion, fecha_asignacion, id_turno)
);

-- =====================================================
-- FACTURACIÓN
-- =====================================================

CREATE TABLE facturas (
                          id_factura BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          id_paciente BIGINT NOT NULL REFERENCES paciente(id_paciente),
                          id_hospitalizacion BIGINT REFERENCES hospitalizaciones(id_hospitalizacion),
                          fecha_emision TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                          subtotal DECIMAL(10,2) NOT NULL CHECK (subtotal >= 0),
                          iva DECIMAL(10,2) NOT NULL DEFAULT 0 CHECK (iva >= 0),
                          total DECIMAL(10,2) NOT NULL,
                          id_estado_factura BIGINT NOT NULL REFERENCES estados_factura(id_estado_factura),
                          activo BOOLEAN NOT NULL DEFAULT TRUE,
                          CHECK (total = subtotal + iva)
);

CREATE TABLE detalle_factura (
                                 id_detalle BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 id_factura BIGINT NOT NULL REFERENCES facturas(id_factura) ON DELETE CASCADE,
                                 concepto VARCHAR(200) NOT NULL,
                                 cantidad INT NOT NULL DEFAULT 1 CHECK (cantidad > 0),
                                 precio_unitario DECIMAL(10,2) NOT NULL CHECK (precio_unitario >= 0),
                                 importe DECIMAL(10,2) NOT NULL,
                                 CHECK (importe = cantidad * precio_unitario)
);

CREATE TABLE cuentas (
                         id_cuenta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         id_paciente BIGINT NOT NULL REFERENCES paciente(id_paciente),
                         id_hospitalizacion BIGINT REFERENCES hospitalizaciones(id_hospitalizacion),
                         fecha_apertura TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                         estado VARCHAR(20) NOT NULL DEFAULT 'Abierta',
                         saldo DECIMAL(10,2) NOT NULL DEFAULT 0.00,
                         activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE pagos (
                       id_pago BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       id_factura BIGINT NOT NULL REFERENCES facturas(id_factura),
                       id_cuenta BIGINT REFERENCES cuentas(id_cuenta),
                       id_metodo_pago BIGINT NOT NULL REFERENCES metodos_pago(id_metodo_pago),
                       monto DECIMAL(10,2) NOT NULL CHECK (monto > 0),
                       fecha_pago TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                       referencia VARCHAR(100),
                       activo BOOLEAN NOT NULL DEFAULT TRUE
);



